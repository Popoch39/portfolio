const PAD = 3;

const round = (n: number) => Math.round(n * 10) / 10;
const fixed = (n: number, digits: number) => Number(n.toFixed(digits));

/** The points of an outline written `M x,y l dx,dy dx,dy …`, as the board's faces all are. */
export function outline(path: string): [number, number][] {
	const numbers = (path.match(/-?\d+(?:\.\d+)?/g) ?? []).map(Number);
	const points: [number, number][] = [];
	let x = 0;
	let y = 0;
	for (let i = 0; i + 1 < numbers.length; i += 2) {
		x = i === 0 ? numbers[i] : x + numbers[i];
		y = i === 0 ? numbers[i + 1] : y + numbers[i + 1];
		points.push([x, y]);
	}
	return points;
}

function boxOf(paths: string[]): Box {
	const points = paths.flatMap(outline);
	const xs = points.map(([x]) => x);
	const ys = points.map(([, y]) => y);
	const x = Math.floor(Math.min(...xs) - PAD);
	const y = Math.floor(Math.min(...ys) - PAD);
	return { x, y, w: Math.ceil(Math.max(...xs) + PAD) - x, h: Math.ceil(Math.max(...ys) + PAD) - y };
}

/** The mockup's generator (mulberry32, seed 39): every visit scatters the parts the same way. */
function generator(seed: number) {
	return () => {
		seed = (seed + 0x6d2b79f5) >>> 0;
		let t = seed;
		t = Math.imul(t ^ (t >>> 15), t | 1);
		t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
		return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
	};
}


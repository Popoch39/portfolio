/** A part's box in the drawing's coordinates, its stroke included. */
export interface Box {
	x: number;
	y: number;
	w: number;
	h: number;
}

export interface Cap {
	/** Top, left and right faces. */
	faces: [string, string, string];
	box: Box;
	/** The cap's centre from its box's corner: the pivot of its in-plane turn. */
	pivot: { x: number; y: number };
	/** Its flight along one iso axis, then a short offset along the other, px of the drawing. */
	main: { x: number; y: number };
	side: { x: number; y: number };
	/** Degrees it turns in the board's plane as it lands. */
	turn: number;
	/** When it sets off and when it clips in, s. */
	delay: number;
	clip: number;
	/** h, j, k, l: the accent caps, their letter and when the accent shows, s. */
	accent?: { letter: string; at: number; label: string };
}

export interface Switch {
	faces: [top: string, left: string, right: string, stem: string, stemTop: string];
	box: Box;
	delay: number;
}

